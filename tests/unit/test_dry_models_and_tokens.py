def test_reports_preserve_positional_construction_and_serialize_dry_fields() -> None:
    """FileReport, CodebaseHealthReport, and DRY dataclasses serialize cleanly."""
    ds = DimensionScores.from_raw((100.0, 100.0, 100.0, 100.0, 100.0), RubricConfig())
    fr = FileReport("src/a.py", False, 20, [], 0, 0, None, ds)
    assert (fr.duplicated_loc, fr.duplication_ratio, fr.dry_score) == (0, 0.0, 100.0)

    cb = CodebaseHealthReport(["src"], 1, 1, 0, 0, 0, ds, ds, ds, {"A": 1}, [fr])
    assert cb.dry.dry_score == 100.0 and cb.dry.clone_groups_count == 0
    assert ReExportedCloneGroup is CloneGroup
    assert ReExportedCloneLocation is CloneLocation
    assert ReExportedDrySummary is DrySummary

    loc = CloneLocation("src/a.py", 10, 20, "fn", 11, 45)
    grp = CloneGroup("DRY-001", "type1", "intra_file", 1.0, 45, 11, [loc])
    metrics = FileDryMetrics(duplicate_blocks=1, duplicated_loc=11, duplication_ratio=55.0, dry_score=72.5, dry_penalty=27.5, findings=["Clean (DRY): ..."])
    summary = DrySummary(total_loc=20, duplicated_loc=11, duplication_ratio=55.0, dry_score=72.5, clone_groups_count=1, type1_groups=1, intra_file_groups=1, clone_groups=[grp])

    assert asdict(metrics)["dry_penalty"] == 27.5
    assert asdict(summary)["clone_groups"][0]["group_id"] == "DRY-001"


def test_slotted_internal_dry_models_enforce_compact_layout() -> None:
    """Internal DRY token and match dataclasses use __slots__ and typed arrays."""
    meta = PyTokenMeta("src/a.py", False, 10, (("fn", 1, 10, 10),))
    block = BlockSpan("fn", 0, 4, 1, 10, 10, 2)
    stream = FileTokenStream(
        "src/a.py",
        "python",
        False,
        10,
        array("I", [16, 17, 18, 19]),
        array("I", [1, 16, 1, 17]),
        array("I", [2, 2, 3, 4]),
        array("B", [1, 0, 1, 0]),
        array("I", [0, 2]),
        (block,),
    )
    match = RawCloneMatch(0, 0, 4, 0, 4, 8, "type1", 1.0)

    for obj in (meta, block, stream, match):
        assert hasattr(obj, "__slots__")
        assert not hasattr(obj, "__dict__")
    assert stream.exact_ids.typecode == "I" and stream.tok_kinds.typecode == "B"


def test_generated_source_positive_and_negative_boundaries() -> None:
    """Standard generated markers, suffixes, Java annotations, and globs filter accurately."""
    assert is_generated_source("proto/user_pb2.py", ["x = 1"]) is True
    assert is_generated_source("proto/user_pb2_grpc.py", ["x = 1"]) is True
    assert is_generated_source("api/client.generated.ts", ["export const x = 1;"]) is True
    assert is_generated_source("api/types.gen.js", ["export const x = 1;"]) is True
    assert is_generated_source("api/msg.pb.ts", ["export const x = 1;"]) is True
    assert is_generated_source("api/msg_pb.js", ["export const x = 1;"]) is True
    assert is_generated_source("src/app.py", ["# @generated by tool", "def f(): pass"]) is True
    assert is_generated_source("src/app.ts", ["/* DO NOT EDIT */", "export const x = 1;"]) is True
    assert is_generated_source("src/app.js", ["// AUTO-GENERATED", "const x = 1;"]) is True
    assert is_generated_source("src/app.ts", ["// Code generated by protoc", "export const x = 1;"]) is True
    assert is_generated_source("src/App.java", ["class App {}"], annotations=("Generated",)) is True
    assert is_generated_source("src/App.java", ["class App {}"], annotations=("javax.annotation.processing.Generated",)) is True
    assert is_generated_source("src/App.java", ["class App {}"], annotations=("jakarta.annotation.Generated",)) is True
    assert is_generated_source("src/gen/foo.py", ["def f(): pass"], exclude_globs=("src/gen/*",)) is True

    # Negative boundaries (Review Focus #3): literal string & @not-generated must NOT skip
    assert is_generated_source("src/app.py", ["# @not-generated", 'def f(): return "generated by user"']) is False
    assert is_generated_source("src/App.java", ["// regular source", "class App {}"]) is False


def test_python_tokens_strip_imports_comments_docstrings_and_type_annotations() -> None:
    """Python extractor strips imports/comments/docstrings/annotations while keeping executable structure."""
    src_a = (
        'import os\n"""Module doc."""\n# top comment\n'
        "def calc(price: float, qty: int) -> float:\n"
        '    """Compute total."""\n'
        "    total: float = price * qty\n"
        '    label = f"sum={total}"\n'
        "    return total\n"
    )
    src_b = (
        "from math import ceil\n"
        "def compute(amount, count):\n"
        "    result = amount * count\n"
        '    msg = f"val={result}"\n'
        "    return result\n"
    )
    interner = TokenInterner()
    s1 = extract_python_tokens(ast.parse(src_a), src_a, PyTokenMeta("a.py", False, 6, (("calc", 4, 8, 5),)), interner)
    s2 = extract_python_tokens(ast.parse(src_b), src_b, PyTokenMeta("b.py", False, 5, (("compute", 2, 5, 4),)), interner)
    assert s1 is not None and s2 is not None
    assert s1.language == "python"
    assert s1.exact_ids.typecode == "I" and s1.tok_kinds.typecode == "B" and s1.stmt_starts.typecode == "I"
    assert list(s1.norm_ids) == list(s2.norm_ids)
    assert TOK_ID in s1.norm_ids and KIND_IDENT in s1.tok_kinds and KIND_LITERAL in s1.tok_kinds
    assert len(s1.stmt_starts) == 3
    assert len(s1.blocks) == 1 and s1.blocks[0].symbol == "calc" and s1.blocks[0].start_tok < s1.blocks[0].end_tok

    gen_src = "# @generated\ndef dup():\n    return 1\n"
    assert extract_python_tokens(ast.parse(gen_src), gen_src, PyTokenMeta("gen.py", False, 2, ()), interner) is None


def test_native_parsers_extract_cst_tokens_and_share_ecmascript_bucket(tmp_path: Path) -> None:
    """Java, JS, and TS parsers populate FileTokenStream in single pass and handle broken/generated files."""
    js_p = tmp_path / "calc.js"
    ts_p = tmp_path / "calc.ts"
    broken_ts = tmp_path / "broken.ts"
    java_p = tmp_path / "OrderSvc.java"
    gen_java = tmp_path / "GenModel.java"

    js_p.write_text('import { log } from "./log";\n// cmt\nexport function sum(a, b) { const out = a + b; log(out); return out; }\n', encoding="utf-8")
    ts_p.write_text('import type { Foo } from "./t";\ninterface Bar { x: number; }\ntype Num = number;\nexport function sum(a: Num, b: number): number { const out: number = a + b; log(out); return out; }\n', encoding="utf-8")
    broken_ts.write_text("export function broken( { return ;;; }\n", encoding="utf-8")
    java_p.write_text("package com.acme;\nimport java.util.List;\n/** Doc. */\npublic class OrderSvc {\n    public int add(int a, int b) {\n        int out = a + b;\n        return out;\n    }\n}\n", encoding="utf-8")
    gen_java.write_text("import jakarta.annotation.Generated;\n@Generated(\"tool\")\npublic class GenModel {\n    public int x() { return 1; }\n}\n", encoding="utf-8")

    interner = TokenInterner()
    js_mod = parse_javascript_file(js_p, "calc.js", False, interner=interner)
    ts_mod = parse_typescript_file(ts_p, "calc.ts", False, interner=interner)
    broken_mod = parse_typescript_file(broken_ts, "broken.ts", False, interner=interner)
    java_mod = parse_java_file(java_p, "OrderSvc.java", False, interner=interner)
    gen_java_mod = parse_java_file(gen_java, "GenModel.java", False, interner=interner)
    no_int_js = parse_javascript_file(js_p, "calc.js", False)

    assert no_int_js.token_stream is None
    assert broken_mod.token_stream is None
    assert gen_java_mod.token_stream is None
    assert js_mod.token_stream is not None and ts_mod.token_stream is not None
    assert js_mod.token_stream.language == "ecmascript"
    assert ts_mod.token_stream.language == "ecmascript"
    assert list(js_mod.token_stream.norm_ids) == list(ts_mod.token_stream.norm_ids)
    assert java_mod.token_stream is not None and java_mod.token_stream.language == "java"
    assert any(b.symbol == "OrderSvc.add" for b in java_mod.token_stream.blocks)
